## Краткий монолог для защиты

Данный скрипт автоматизирует подключение worker-узлов к Docker Swarm кластеру в рамках инфраструктуры, разворачиваемой через Vagrant. Его задача — взять worker-токен и IP-адрес менеджера, которые manager-узел заранее сохранил в общую папку, и выполнить команду `docker swarm join`. Ключевая особенность скрипта — его идемпотентность: повторный запуск не вызовет ошибку, потому что в самом начале проверяется, не находится ли узел уже в Swarm. Также реализована защитная валидация входных данных: скрипт проверяет существование файлов, корректность префикса токена (`SWMTKN-1-`) и формат IP-адреса, очищает данные от лишних символов (особенно `\r` от Windows-окончаний строк, что часто ломает работу в смешанных средах). Благодаря `set -e` любая ошибка немедленно прерывает выполнение, а подробное логирование с префиксом `[swarm-join]` упрощает отладку при провижининге нескольких машин одновременно.

