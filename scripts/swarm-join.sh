## Возможные вопросы на защите и ответы

**1. Почему именно порт 2377?**
Это стандартный порт Docker Swarm для управления кластером (cluster management communications). Также используются 7946 (TCP/UDP) для коммуникации между узлами и 4789 (UDP) для overlay-сетей.

**2. Зачем нужен `tr -d '\r' | xargs`?**
`tr -d '\r'` удаляет символы возврата каретки, которые могут попасть в файл, если он создавался в Windows-среде. `xargs` без аргументов удобно обрезает лишние пробелы и переводы строк с обеих сторон.

**3. Что делает `set -e`?**
Включает режим, при котором скрипт сразу завершится, если любая команда вернёт ненулевой код возврата. Это защита от молчаливых ошибок.

**4. Почему проверяется префикс `SWMTKN-1-`?**
Это стандартный формат токена Docker Swarm. Если префикс не совпадает — значит файл повреждён, пуст или содержит мусор, и подключаться бесполезно.

**5. Зачем нужна проверка `Swarm: active`?**
Для идемпотентности — чтобы при повторном `vagrant provision` скрипт не пытался заново присоединить уже подключённый узел и не падал с ошибкой.

**6. Откуда берутся файлы с токеном и IP?**
Их создаёт manager-узел при своём провижининге командой `docker swarm init` и сохраняет в общую (shared) папку, доступную всем VM через Vagrant synced folder.

**7. В чём разница между worker и manager токеном?**
Manager-токен даёт узлу права управления кластером (участие в Raft-консенсусе), worker-токен — только выполнение задач. Использование worker-токена ограничивает узел ролью исполнителя.

**8. Что если manager-узел недоступен?**
Команда `docker swarm join` завершится с ошибкой, `set -e` остановит скрипт, и Vagrant покажет ошибку провижининга — это правильное поведение, потому что без менеджера кластера нет.

**9. Почему используется `xxd` при ошибке токена?**
Для диагностики: hex-дамп показывает все байты файла, включая невидимые символы (BOM, пробелы, переводы строк), что помогает понять, почему токен не прошёл валидацию.

**10. Можно ли запускать этот скрипт вручную?**
Да, если файлы с токеном и IP уже существуют. Скрипт самодостаточен и не зависит от Vagrant, его можно использовать для ручного подключения нового worker-узла.