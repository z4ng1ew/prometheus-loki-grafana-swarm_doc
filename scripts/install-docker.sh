## Возможные вопросы и ответы

**В: Зачем нужен `set -e` и одновременно `|| true`?**
О: `set -e` обеспечивает остановку скрипта при любой реальной ошибке (например, если не установится Docker). А `|| true` применяется точечно к тем командам, которые могут «законно» завершиться с ненулевым кодом — например, `growpart` возвращает ошибку, если раздел уже расширен. Без `|| true` в этих местах `set -e` остановил бы скрипт на безобидной ситуации.

**В: Почему Docker ставится из репозитория Docker, а не из стандартного Ubuntu?**
О: В репозиториях Ubuntu находится пакет `docker.io`, который обычно отстаёт на несколько версий и не включает плагины buildx и compose. Официальный репозиторий Docker предоставляет актуальную версию и все необходимые компоненты.

**В: Зачем нужен `DEBIAN_FRONTEND=noninteractive`?**
О: При автоматической установке пакетов (через Vagrant provisioner) нет интерактивного терминала. Без этой переменной некоторые пакеты могут вывести диалоговое окно (например, выбор конфигурации grub при обновлении ядра), и скрипт зависнет в ожидании ввода.

**В: Что произойдёт, если второй сетевой интерфейс не найден?**
О: Переменная `SECOND_IFACE` будет пустой, условие `if [ -n "$SECOND_IFACE" ]` не выполнится, и блок настройки сети просто пропустится. Скрипт продолжит установку Docker.

**В: Зачем `chmod 600` на netplan-файл?**
О: Netplan начиная с определённых версий выдаёт предупреждение или отказывается применять конфигурацию, если файлы доступны для чтения другим пользователям. Права 600 (только root) — требование безопасности, т.к. в конфиге могут содержаться пароли Wi-Fi и подобные данные.

**В: Зачем `usermod -aG docker vagrant`?**
О: По умолчанию Docker-сокет `/var/run/docker.sock` доступен только root и членам группы docker. Без добавления пользователя vagrant в эту группу все команды docker пришлось бы выполнять через `sudo`, что неудобно при разработке.

**В: Что такое containerd.io и зачем он нужен отдельно?**
О: Containerd — это низкоуровневый container runtime, который непосредственно управляет жизненным циклом контейнеров (создание, запуск, остановка). Docker Engine использует containerd как бэкенд. Он поставляется отдельным пакетом, потому что может использоваться и без Docker (например, с Kubernetes напрямую).

**В: Почему `sleep 3` после `netplan apply`?**
О: После применения конфигурации netplan интерфейс поднимается и DHCP-клиент отправляет запрос на получение IP-адреса. Этот процесс (DHCP Discover → Offer → Request → Acknowledge) занимает 1–3 секунды. Без паузы последующие команды могут выполняться до получения IP.

**В: Можно ли запускать скрипт повторно?**
О: Да, скрипт идемпотентен. `growpart` и `resize2fs` безопасно завершатся, если расширение уже выполнено. `apt-get install` переустановит или обновит пакеты. `usermod` не дублирует группу. `systemctl enable/start` не ломается при повторном вызове.