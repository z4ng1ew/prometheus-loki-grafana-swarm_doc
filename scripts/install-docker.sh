## Монолог для защиты

Данный скрипт представляет собой полностью автоматизированный provisioning-сценарий, вызываемый Vagrant при первичном создании виртуальной машины, и решает три ключевые задачи подготовки рабочего окружения. **Во-первых**, он расширяет корневой раздел диска и файловую систему до полного размера виртуального диска, поскольку облачные образы Ubuntu по умолчанию создаются с минимальным разделом, и без расширения может не хватить места для Docker-образов. **Во-вторых**, скрипт обнаруживает и настраивает второй сетевой интерфейс через netplan с DHCP — это необходимо для private-network коммуникации между несколькими виртуальными машинами в кластере, так как Vagrant создаёт интерфейс, но не всегда автоматически назначает ему IP-адрес. **В-третьих**, выполняется установка Docker CE из официального репозитория Docker по рекомендованной процедуре: добавление GPG-ключа, подключение репозитория для конкретной версии Ubuntu, установка пяти компонентов (Engine, CLI, containerd, buildx, compose-plugin) и настройка прав пользователя vagrant для беспарольной работы с Docker. Особенностью скрипта является его идемпотентность и отказоустойчивость — конструкции `|| true` позволяют безопасно перезапускать provisioning без ошибок, а переменная `DEBIAN_FRONTEND=noninteractive` гарантирует полностью автоматическое выполнение без пользовательского ввода.

