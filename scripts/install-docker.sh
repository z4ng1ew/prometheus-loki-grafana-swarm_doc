# до максимально доступного размера (занимает всё свободное пространство)
# «|| true» — если раздел уже максимального размера, growpart вернёт ошибку,
# но мы её игнорируем, чтобы скрипт не прервался (set -e)

resize2fs "$ROOT_DEVICE" || true
# Расширяем файловую систему ext2/ext3/ext4 на разделе до размера раздела
# Без этой команды ФС не увидит новое пространство, даже если раздел расширен
# «|| true» — аналогично: если ФС не ext или уже расширена, игнорируем ошибку

echo "[install-docker] Свободное место ПОСЛЕ расширения:"
df -h /
# Показываем результат расширения — для контроля

# =================== БЛОК 2: НАСТРОЙКА СЕТЕВОГО ИНТЕРФЕЙСА ===================

echo "[install-docker] Текущие интерфейсы:"
ip -4 addr show
# Выводим все сетевые интерфейсы с IPv4-адресами
# -4 — фильтрует только IPv4, убирает IPv6

SECOND_IFACE=$(ip -o link show | awk -F': ' '$2 != "lo" && $2 !~ /^vir/ {print $2}' | sed 's/@.*//' | sort | sed -n '2p')
# Ищем имя второго сетевого интерфейса (не считая lo и виртуальных vir*):
# ip -o link show  — выводит все интерфейсы в однострочном формате
# awk -F': '       — разделитель «: », берём второе поле (имя интерфейса)
# $2 != "lo"       — исключаем loopback
# $2 !~ /^vir/     — исключаем виртуальные мосты (virbr0 и т.п.)
# sed 's/@.*//'    — убираем суффикс (например, «eth0@if2» → «eth0»)
# sort              — сортируем по имени
# sed -n '2p'       — берём вторую строку, т.е. второй интерфейс
# Первый интерфейс обычно NAT от Vagrant, второй — host-only / private network

if [ -n "$SECOND_IFACE" ]; then
    # Если второй интерфейс найден (переменная не пустая)
    echo "[install-docker] Найден второй интерфейс: $SECOND_IFACE"
    
    if ! ip -4 addr show "$SECOND_IFACE" | grep -q "inet "; then
        # Проверяем, есть ли у второго интерфейса IPv4-адрес
        # grep -q — тихий режим, только код возврата
        # Если адреса НЕТ (! перед командой), настраиваем через netplan
        
        echo "[install-docker] У $SECOND_IFACE нет IP, поднимаем через netplan"
        
        cat > /etc/netplan/60-vagrant.yaml << NETPLAN
network:
  version: 2
  renderer: networkd
  ethernets:
    $SECOND_IFACE:
      dhcp4: true
NETPLAN
        # Создаём конфигурационный файл netplan для второго интерфейса
        # version: 2        — версия формата netplan
        # renderer: networkd — используем systemd-networkd как бэкенд
        # dhcp4: true        — получить IPv4-адрес по DHCP автоматически
        # Имя файла 60-* обеспечивает приоритет выше стандартных (50-*),
        # но ниже пользовательских (99-*)
        
        chmod 600 /etc/netplan/60-vagrant.yaml
        # Устанавливаем права «только владелец (root) читает/пишет»
        # Netplan требует ограниченных прав на конфиг-файлы (безопасность)
        
        netplan apply || true
        # Применяем сетевую конфигурацию без перезагрузки
        # «|| true» — если netplan выдаст предупреждение/ошибку, не падаем
        
        sleep 3
        # Ждём 3 секунды, пока DHCP-клиент получит IP-адрес от сервера
    fi
fi

echo "[install-docker] Все IP после настройки:"
ip -4 addr show
# Выводим финальное состояние всех интерфейсов для проверки

# =================== БЛОК 3: УСТАНОВКА DOCKER ========================

apt-get install -y -q ca-certificates curl gnupg lsb-release
# Устанавливаем зависимости, необходимые для добавления стороннего репозитория:
# ca-certificates — корневые SSL-сертификаты (для HTTPS)
# curl            — для скачивания GPG-ключа Docker
# gnupg           — для работы с криптографическими ключами (gpg --dearmor)
# lsb-release     — для определения кодового имени дистрибутива (focal, jammy и т.д.)

install -m 0755 -d /etc/apt/keyrings
# Создаём каталог для хранения GPG-ключей репозиториев
# install -m 0755 -d — создаёт директорию с правами rwxr-xr-x
# Это рекомендованный Docker'ом путь для хранения ключей (с apt 2.4+)

curl -fsSL https://download.docker.com/linux/ubuntu/gpg \
  | gpg --dearmor --yes -o /etc/apt/keyrings/docker.gpg
# Скачиваем публичный GPG-ключ Docker и конвертируем его в бинарный формат:
# curl -fsSL: -f — ошибка при HTTP 4xx/5xx, -s — тихо, -S — показывать ошибки, -L — следовать редиректам
# gpg --dearmor — конвертирует ASCII-armored ключ в бинарный (.gpg)
# --yes — перезаписать файл без подтверждения
# Этот ключ нужен apt для верификации подлинности пакетов из репозитория Docker

chmod a+r /etc/apt/keyrings/docker.gpg
# Даём всем пользователям право на чтение ключа,
# чтобы apt (который может работать от разных пользователей) мог его прочитать

echo \
  "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.gpg] \
  https://download.docker.com/linux/ubuntu \
  $(. /etc/os-release && echo "$VERSION_CODENAME") stable" \
  > /etc/apt/sources.list.d/docker.list
# Добавляем официальный репозиторий Docker в список источников apt:
# arch=$(...) — архитектура процессора (amd64, arm64 и т.д.)
# signed-by=... — указываем ключ для проверки подписей пакетов
# $VERSION_CODENAME — кодовое имя Ubuntu (jammy, noble и т.п.),
#   считывается из /etc/os-release через sourcing (. — аналог source)
# stable — ветка репозитория (есть ещё test и nightly)
# Файл кладётся в /etc/apt/sources.list.d/, чтобы не модифицировать основной sources.list

apt-get update -q
# Обновляем индекс пакетов повторно — теперь apt «видит» пакеты из репозитория Docker

apt-get install -y -q docker-ce docker-ce-cli containerd.io \
  docker-buildx-plugin docker-compose-plugin
# Устанавливаем Docker и все его компоненты:
# docker-ce            — Docker Engine (Community Edition), серверная часть (демон dockerd)
# docker-ce-cli        — CLI-клиент docker для управления контейнерами из терминала
# containerd.io        — среда выполнения контейнеров (container runtime),
#                        на которой работает Docker
# docker-buildx-plugin — расширенный сборщик образов (поддержка мульти-архитектурных сборок)
# docker-compose-plugin — плагин для оркестрации многоконтейнерных приложений
#                         (замена устаревшего docker-compose v1)

usermod -aG docker vagrant
# Добавляем пользователя vagrant в группу docker,
# чтобы он мог выполнять команды docker без sudo
# -a — append (добавить, не заменяя другие группы), -G — указание группы

systemctl enable docker
# Включаем автозапуск службы Docker при загрузке системы
# (создаёт симлинк в systemd)

systemctl start docker
# Запускаем службу Docker прямо сейчас (без перезагрузки ВМ)

echo "[install-docker] Готово. Версия: $(docker --version)"
# Выводим установленную версию Docker — финальная проверка успешности установки
```

