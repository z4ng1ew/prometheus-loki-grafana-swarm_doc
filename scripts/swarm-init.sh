# Монолог для защиты

Данный скрипт отвечает за инициализацию Docker Swarm кластера на manager-ноде и является отправной точкой для построения всей кластерной инфраструктуры. Скрипт автоматически определяет корректный IP-адрес менеджера из host-only подсети Vagrant (192.168.56.0/24), исключая NAT-интерфейс, который одинаков у всех виртуальных машин и непригоден для межнодового взаимодействия. После определения IP происходит инициализация Swarm с явным указанием `--advertise-addr`, что гарантирует доступность менеджера для worker-нод. Ключевая особенность скрипта — идемпотентность: перед инициализацией проверяется, не запущен ли Swarm уже, что позволяет безопасно перезапускать provisioning. После создания кластера скрипт извлекает join-токен для worker-нод и сохраняет его вместе с IP менеджера в синхронизированную папку Vagrant — это обеспечивает автоматическую передачу данных между виртуальными машинами без необходимости ручного копирования или сетевых запросов, после чего worker-скрипты могут прочитать эти файлы и автоматически присоединиться к кластеру.