# Ответы на возможные вопросы

**1. Зачем нужен `set -e`?**
Чтобы скрипт немедленно прекращал выполнение при любой ошибке. Без него, если, например, `docker swarm init` упадёт, скрипт продолжит работу и запишет невалидные данные в файлы, что приведёт к скрытым ошибкам на worker-нодах.

**2. Почему ищем именно подсеть 192.168.56.0/24?**
Это стандартная host-only сеть VirtualBox/Vagrant. У каждой VM есть также NAT-интерфейс (10.0.2.15), который одинаков на всех машинах и недоступен между ними. Поэтому для межнодового общения Swarm нужен именно host-only адрес.

**3. Зачем `--advertise-addr`?**
Docker Swarm должен знать, по какому IP другие ноды будут к нему обращаться. Без явного указания Docker может автоматически выбрать NAT-адрес 10.0.2.15, и тогда worker-ноды не смогут связаться с менеджером.

**4. Почему скрипт идемпотентен (проверка `Swarm: active`)?**
Vagrant может повторно запускать provisioning (например, при `vagrant provision` или `vagrant reload --provision`). Повторный `docker swarm init` вернёт ошибку, поэтому мы проверяем состояние и пропускаем инициализацию, если Swarm уже активен.

**5. Зачем сохранять токен и IP в файлы?**
Эта директория `/home/vagrant/project/` является синхронизированной папкой Vagrant (synced folder). Файлы, записанные здесь на manager-ноде, автоматически становятся доступны на worker-нодах через общую файловую систему хоста. Это простейший механизм передачи данных между VM без сети.

**6. Почему `echo -n` без перевода строки?**
Чтобы при чтении файла (например, через `cat` или `$(< file)`) не попал лишний символ `\n`, который может сломать команду `docker swarm join`.

**7. Почему `chown vagrant:vagrant`?**
Скрипт provisioning выполняется от имени root, поэтому созданные файлы принадлежат root. Меняем владельца на vagrant, чтобы пользователь мог читать и модифицировать эти файлы без sudo.

**8. Что покажет `docker node ls` на этом этапе?**
Только одну ноду — саму manager-ноду со статусом `Leader` и состоянием `Ready`. После присоединения worker-нод список пополнится.

